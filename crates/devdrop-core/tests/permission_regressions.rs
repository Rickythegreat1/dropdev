//! Independent permission-preservation behavior checks. Every file is generated
//! under tempfile; no user worktree, secret, ACL, or ownership is modified.
#[cfg(unix)]
mod unix {
    use devdrop_core::local::{Engine, Pair};
    use serde_json::Value;
    use std::{
        fs,
        os::unix::fs::{MetadataExt, PermissionsExt},
        path::{Path, PathBuf},
    };

    struct Workspace {
        _temp: tempfile::TempDir,
        source: PathBuf,
        target: PathBuf,
        state: PathBuf,
    }
    impl Workspace {
        fn new() -> Self {
            let temp = tempfile::tempdir().unwrap();
            let base = fs::canonicalize(temp.path()).unwrap();
            let source = base.join("source");
            let target = base.join("target");
            let state = base.join("metadata");
            fs::create_dir(&source).unwrap();
            fs::create_dir(&target).unwrap();
            mode(&source, 0o700);
            mode(&target, 0o700);
            Self {
                _temp: temp,
                source,
                target,
                state,
            }
        }
        fn engine(&self) -> Engine {
            Engine::open(&self.state).unwrap()
        }
        fn register(&self, e: &Engine) -> Pair {
            e.register("generated permission review", &self.source, &self.target)
                .unwrap()
        }
        fn source(&self, path: &str, bytes: &[u8], permissions: u32) {
            let full = self.source.join(path);
            if let Some(parent) = full.parent() {
                fs::create_dir_all(parent).unwrap();
            }
            fs::write(&full, bytes).unwrap();
            mode(&full, permissions);
        }
    }
    fn mode(path: &Path, value: u32) {
        fs::set_permissions(path, fs::Permissions::from_mode(value)).unwrap();
    }
    fn actual_mode(path: &Path) -> u32 {
        fs::metadata(path).unwrap().mode() & 0o7777
    }
    fn initial(e: &Engine, pair: &Pair) {
        let p = e.preview(&pair.id).unwrap();
        e.apply(&p.id, &p.id, true, true).unwrap();
    }

    #[test]
    fn owner_only_executable_and_readonly_modes_are_copied_exactly() {
        let w = Workspace::new();
        w.source("run.sh", b"#!/bin/sh\nprintf generated\n", 0o700);
        w.source("readonly.txt", b"generated readonly bytes", 0o400);
        let e = w.engine();
        let pair = w.register(&e);
        let p = e.preview(&pair.id).unwrap();
        assert!(p.operations.iter().all(|op| !op.permission_widening));
        e.apply(&p.id, &p.id, true, false).unwrap();
        assert_eq!(actual_mode(&w.target.join("run.sh")), 0o700);
        assert_eq!(actual_mode(&w.target.join("readonly.txt")), 0o400);
        assert_eq!(
            fs::read(w.target.join("readonly.txt")).unwrap(),
            b"generated readonly bytes"
        );
    }

    #[test]
    fn new_group_or_other_grants_require_separate_widening_consent() {
        let w = Workspace::new();
        w.source("shared.txt", b"generated shared bytes", 0o640);
        let e = w.engine();
        let pair = w.register(&e);
        let p = e.preview(&pair.id).unwrap();
        assert!(p.operations[0].permission_widening);
        assert!(e.apply(&p.id, &p.id, true, false).is_err());
        assert!(!w.target.join("shared.txt").exists());
        e.apply(&p.id, &p.id, true, true).unwrap();
        assert_eq!(actual_mode(&w.target.join("shared.txt")), 0o640);
    }

    #[test]
    fn metadata_only_change_is_explicit_and_widening_is_not_silent() {
        let w = Workspace::new();
        w.source("run.sh", b"generated fixed content", 0o600);
        let e = w.engine();
        let pair = w.register(&e);
        initial(&e, &pair);
        mode(&w.source.join("run.sh"), 0o700);
        let p = e.preview(&pair.id).unwrap();
        assert_eq!(p.operations.len(), 1);
        let op = &p.operations[0];
        assert_eq!(op.kind, "permissions");
        assert_eq!(op.before, op.after);
        assert!(op.permission_widening);
        assert!(e.apply(&p.id, &p.id, true, false).is_err());
        assert_eq!(actual_mode(&w.target.join("run.sh")), 0o600);
        e.apply(&p.id, &p.id, true, true).unwrap();
        assert_eq!(actual_mode(&w.target.join("run.sh")), 0o700);
        assert!(e.preview(&pair.id).unwrap().operations.is_empty());
    }

    #[test]
    fn source_and_target_chmod_only_changes_stale_existing_previews() {
        for side in ["source", "target"] {
            let w = Workspace::new();
            w.source("work.txt", b"first generated bytes", 0o600);
            let e = w.engine();
            let pair = w.register(&e);
            initial(&e, &pair);
            w.source("work.txt", b"new generated bytes", 0o600);
            let p = e.preview(&pair.id).unwrap();
            let changed = if side == "source" {
                &w.source
            } else {
                &w.target
            };
            mode(&changed.join("work.txt"), 0o700);
            assert!(e.apply(&p.id, &p.id, true, true).is_err());
            assert_eq!(
                fs::read(w.target.join("work.txt")).unwrap(),
                b"first generated bytes"
            );
        }
    }

    #[test]
    fn directory_security_metadata_change_stales_preview() {
        for side in ["source", "target"] {
            let w = Workspace::new();
            w.source("work.txt", b"generated bytes", 0o600);
            let e = w.engine();
            let pair = w.register(&e);
            let p = e.preview(&pair.id).unwrap();
            mode(
                if side == "source" {
                    &w.source
                } else {
                    &w.target
                },
                0o750,
            );
            assert!(e.apply(&p.id, &p.id, true, true).is_err());
            assert!(!w.target.join("work.txt").exists());
        }
    }

    #[test]
    fn equivalent_permission_directory_swap_is_not_trusted() {
        let w = Workspace::new();
        w.source("nested/work.txt", b"generated same inode content", 0o600);
        mode(&w.source.join("nested"), 0o700);
        let e = w.engine();
        let pair = w.register(&e);
        let p = e.preview(&pair.id).unwrap();
        let preserved = w._temp.path().join("old-parent");
        fs::rename(w.source.join("nested"), &preserved).unwrap();
        fs::create_dir(w.source.join("nested")).unwrap();
        mode(&w.source.join("nested"), 0o700);
        fs::rename(preserved.join("work.txt"), w.source.join("nested/work.txt")).unwrap();
        assert!(e.apply(&p.id, &p.id, true, true).is_err());
        assert!(!w.target.join("nested/work.txt").exists());
    }

    #[test]
    fn special_permission_bits_are_refused_without_mutating_replica() {
        for unsupported in [0o4700, 0o2700, 0o1700] {
            let w = Workspace::new();
            w.source("work.txt", b"generated unsupported mode", unsupported);
            let e = w.engine();
            let pair = w.register(&e);
            assert!(
                e.preview(&pair.id).is_err(),
                "accepted unsupported mode {unsupported:o}"
            );
            assert!(!w.target.join("work.txt").exists());
        }
    }

    #[test]
    fn source_extended_attributes_are_refused_without_serializing_values() {
        let w = Workspace::new();
        w.source("work.txt", b"generated xattr fixture", 0o600);
        let canary = b"GENERATED_PRIVATE_XATTR_CANARY_59027";
        xattr::set(
            w.source.join("work.txt"),
            "user.devdrop_permission_review",
            canary,
        )
        .unwrap();
        let e = w.engine();
        let pair = w.register(&e);
        let error = e.preview(&pair.id).unwrap_err().to_string();
        assert!(!error.contains("GENERATED_PRIVATE_XATTR_CANARY"));
        assert!(!e
            .events()
            .unwrap()
            .to_string()
            .contains("GENERATED_PRIVATE_XATTR_CANARY"));
        assert!(!w.target.join("work.txt").exists());
    }

    fn replaced_executable() -> (Workspace, Engine, String, u64) {
        let w = Workspace::new();
        w.source("work.txt", b"original executable bytes", 0o700);
        let e = w.engine();
        let pair = w.register(&e);
        initial(&e, &pair);
        let original_inode = fs::metadata(w.target.join("work.txt")).unwrap().ino();
        w.source("work.txt", b"replacement bytes", 0o600);
        let p = e.preview(&pair.id).unwrap();
        assert!(!p.operations[0].permission_widening);
        e.apply(&p.id, &p.id, true, false).unwrap();
        (w, e, p.id, original_inode)
    }

    #[test]
    fn rollback_restores_retained_inode_and_requires_its_own_widening_consent() {
        let (w, e, id, original_inode) = replaced_executable();
        assert_eq!(actual_mode(&w.target.join("work.txt")), 0o600);
        let rollback = e.rollback_preview(&id).unwrap();
        assert!(rollback.operations[0].permission_widening);
        assert!(e.apply(&rollback.id, &rollback.id, true, false).is_err());
        assert_eq!(
            fs::read(w.target.join("work.txt")).unwrap(),
            b"replacement bytes"
        );
        e.apply(&rollback.id, &rollback.id, true, true).unwrap();
        assert_eq!(actual_mode(&w.target.join("work.txt")), 0o700);
        assert_eq!(
            fs::metadata(w.target.join("work.txt")).unwrap().ino(),
            original_inode
        );
        assert_eq!(
            fs::read(w.target.join("work.txt")).unwrap(),
            b"original executable bytes"
        );
    }

    #[test]
    fn missing_modified_or_substituted_retained_inode_blocks_rollback() {
        for fault in ["missing", "mode", "substitute"] {
            let (w, e, id, _) = replaced_executable();
            let retained = w.target.join(format!(".devdrop-recovery-{id}-0/previous"));
            match fault {
                "missing" => fs::remove_file(&retained).unwrap(),
                "mode" => mode(&retained, 0o600),
                _ => {
                    fs::remove_file(&retained).unwrap();
                    fs::write(&retained, b"original executable bytes").unwrap();
                    mode(&retained, 0o700);
                }
            }
            assert!(
                e.rollback_preview(&id).is_err(),
                "accepted {fault} recovery evidence"
            );
            assert_eq!(
                fs::read(w.target.join("work.txt")).unwrap(),
                b"replacement bytes"
            );
        }
    }

    #[test]
    fn metadata_only_replacement_does_not_chmod_an_unrelated_hard_link() {
        let w = Workspace::new();
        w.source("work.txt", b"generated shared inode bytes", 0o700);
        let e = w.engine();
        let pair = w.register(&e);
        initial(&e, &pair);
        let unrelated = w._temp.path().join("unrelated-hard-link");
        fs::hard_link(w.target.join("work.txt"), &unrelated).unwrap();
        mode(&w.source.join("work.txt"), 0o600);
        let p = e.preview(&pair.id).unwrap();
        assert_eq!(p.operations[0].kind, "permissions");
        e.apply(&p.id, &p.id, true, false).unwrap();
        assert_eq!(actual_mode(&w.target.join("work.txt")), 0o600);
        assert_eq!(actual_mode(&unrelated), 0o700);
        assert_ne!(
            fs::metadata(w.target.join("work.txt")).unwrap().ino(),
            fs::metadata(unrelated).unwrap().ino()
        );
    }

    #[test]
    fn legacy_plans_without_metadata_snapshots_cannot_apply_or_rollback() {
        let w = Workspace::new();
        w.source("work.txt", b"generated legacy fixture", 0o600);
        let e = w.engine();
        let pair = w.register(&e);
        let p = e.preview(&pair.id).unwrap();
        drop(e);
        strip_plan_metadata(&w.state, &p.id);
        let e = w.engine();
        assert!(e.apply(&p.id, &p.id, true, true).is_err());
        assert!(!w.target.join("work.txt").exists());
        let fresh = e.preview(&pair.id).unwrap();
        e.apply(&fresh.id, &fresh.id, true, true).unwrap();
        drop(e);
        strip_plan_metadata(&w.state, &fresh.id);
        let e = w.engine();
        assert!(e.rollback_preview(&fresh.id).is_err());
        assert_eq!(
            fs::read(w.target.join("work.txt")).unwrap(),
            b"generated legacy fixture"
        );
    }

    fn strip_plan_metadata(state: &Path, id: &str) {
        let db = rusqlite::Connection::open(state.join("metadata.sqlite3")).unwrap();
        let body: String = db
            .query_row("SELECT body FROM plans WHERE id=?1", [id], |row| row.get(0))
            .unwrap();
        let mut value: Value = serde_json::from_str(&body).unwrap();
        for field in ["metadata_version", "source_metadata", "target_metadata"] {
            value.as_object_mut().unwrap().remove(field);
        }
        db.execute(
            "UPDATE plans SET body=?1 WHERE id=?2",
            rusqlite::params![serde_json::to_string(&value).unwrap(), id],
        )
        .unwrap();
    }
}
